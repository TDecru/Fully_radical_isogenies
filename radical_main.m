/*
  Proof of concept for "Getting to the right root: radical isogenies of every degree".

  We evaluate the action of prod_l (l, pi - 1)^{e_l} on supersingular curves over F_p in two ways:
    "velu"  : Velu's formulae for every degree, with sampled kernel points;
    "ours"  : the inversion-free radical steps of this work (Algorithm 5.2), starting each chain from
              the x-only Tate normal form of Proposition 5.5.
  Negative exponents are handled by the quadratic twist. The results are compared up to
  F_p-isomorphism, and applying the inverse key must lead back to the starting curve.
  This is a correctness check only; no attempt is made at efficiency or constant time.
*/

// ---------------------------------------------------------------- parameters

ls := PrimesInInterval(3, 97);                    // odd degrees l
L  := &*ls;
f  := 1;
while not IsPrime(4*f*L - 1) do f +:= 2; end while;
p  := 4*f*L - 1;                                  // p = 3 mod 4, all l divide p + 1
F  := GF(p);

CT   := true;                                     // inversion by exponentiation, as in constant-time code
Inv  := func< x | CT select x^(p-2) else x^-1 >;
Root := func< v, N | v^InverseMod(N, p-1) >;      // odd N | p+1: the unique N-th root in F_p


// ---------------------------------------------------------------- Velu

// Random point of order N (N prime).
KernelPoint := function(E, N)
  repeat P := ((p+1) div N)*Random(E); until not IsZero(P);
  return P;
end function;

// Velu's formulae for a kernel of odd prime order l generated by P.
VeluStep := function(E, P, l)
  a1, a2, a3, a4, a6 := Explode(aInvariants(E));
  b2 := a1^2 + 4*a2;
  v := F!0; w := F!0; Q := P;
  for k in [1..(l-1) div 2] do
    x := Q[1]; y := Q[2];
    gx := 3*x^2 + 2*a2*x + a4 - a1*y;
    gy := -2*y - a1*x - a3;
    vQ := 2*gx - a1*gy;
    v +:= vQ;  w +:= gy^2 + x*vQ;
    Q +:= P;
  end for;
  return EllipticCurve([a1, a2, a3, a4 - 5*v, a6 - b2*v - 7*w]);
end function;


// ---------------------------------------------------------------- Tate normal form

// Tate normal form (B : C : Z) of (E, P) from x(P) only, without inversions (Proposition 5.5).
TateXonly := function(E, P)
  b2, b4, b6 := Explode(bInvariants(E));
  x  := P[1];
  Fx := 4*x^3 + b2*x^2 + 2*b4*x + b6;
  Gx := 6*x^2 + b2*x + b4;
  W  := (12*x + b2)*Fx - Gx^2;
  return -W^3, 16*Fx^2*(4*Fx^2 - Gx*W), 64*Fx^4;
end function;


// ---------------------------------------------------------------- radical steps

// Scaled x-coordinates X[k]/D[k] of [k]P, 2 <= k <= N-2, via Lemma 5.1 and x([N-k]P) = x([k]P).
Multiples := function(B, C, Z, N)
  A  := Z - C;  a3 := -B*Z^2;  h := N div 2;
  X  := [F!0 : k in [1..N]];  D := [F!1 : k in [1..N]];
  X[2] := B*Z;
  if h ge 3 then X[3] := C*Z; end if;
  for k in [4..h] do
    t1   := a3*D[k-1];
    X[k] := t1*(t1 + A*X[k-1])*D[k-2] - X[k-2]*X[k-1]^2;
    D[k] := X[k-1]^2*D[k-2];
  end for;
  for k in [h+1..N-2] do X[k] := X[N-k]; D[k] := D[N-k]; end for;
  return A, a3, X, D;
end function;

// One radical N-step (B : C : Z) -> (B' : C' : Z'), projective and inversion-free (Algorithm 5.2).
StepOurs := function(B, C, Z, N)
  A, a3, X, D := Multiples(B, C, Z, N);

  // radical and root
  mu := a3^2*&*[X[k] : k in [2..N-2]];
  g0 := Root(-&*[D[k] : k in [2..N-2]]*mu^(N-1), N);

  // terms e_i via prefix products
  Xi := [g0];  H := [F!1];
  for i in [2..N-2] do
    Append(~Xi, Xi[i-1]*g0*X[i]);
    Append(~H,  H[i-1]*mu*D[i]);
  end for;
  e  := [Xi[i]*H[N-1-i] : i in [1..N-2]];
  n  := N - 2;  eb := e[n];

  // sums
  Q1  := &+e;
  Q11 := &+[F| t^2 : t in e];
  Q2  := &+[F| e[i]*e[i+1] : i in [1..n-1]];
  Q3  := &+[F| e[i]*e[i+1]*e[i+2] : i in [1..n-2]];
  Q12 := &+[F| e[i]^2*e[i+1] : i in [1..n-1]];

  // assembly: u = U/g^3, s = S/g^2, r = R/(2 g^5)
  g   := g0*mu*H[N-2];  kap := B*Z*g0;
  V   := mu^2*Q3 - mu*g*eb^2 - g^2*eb;
  U   := g^3 + 3*kap*Q1*g^2 - mu*V;
  S   := kap*(g*(2*Q1 + eb) - mu*Q2);
  R   := 2*kap*(g*Q1 + mu*Q2 - g*eb)*(g^3 - mu*V) + 3*kap^2*(Q1^2 - Q11)*g^3 - 2*kap^2*mu*Q12*g^2;
  return g*(2*B*g^5 + 2*A*S*g^3 + 2*Z*S^2*g - 3*Z*R), 2*U*(Z*U - g*(A*g^2 + 2*S*Z)), 2*Z*U^2;
end function;


// ---------------------------------------------------------------- the action

// Quadratic twist by -1 (a non-square since p = 3 mod 4), on the short model y^2 = x^3 - 27c4 x - 54c6.
Twist := function(E)
  c4, c6 := Explode(cInvariants(E));
  return EllipticCurve([F| -27*c4, 54*c6]);
end function;

// Action of prod_l (l, pi - 1)^{e_l}. Radical steps are used for l >= 5, Velu for l = 3.
// For e_l < 0 we use (l, pi + 1) = twist o (l, pi - 1) o twist.
Act := function(E, e, method)
  for i in [1..#ls] do
    l := ls[i];  k := Abs(e[i]);
    if k eq 0 then continue; end if;
    if e[i] lt 0 then E := Twist(E); end if;

    if method eq "velu" or l lt 5 then
      for t in [1..k] do E := VeluStep(E, KernelPoint(E, l), l); end for;
    else
      P := KernelPoint(E, l);                         // one kernel point for the whole chain
      B, C, Z := TateXonly(E, P);
      for t in [1..k] do B, C, Z := StepOurs(B, C, Z, l); end for;
      iZ := Inv(Z);  b := B*iZ;  c := C*iZ;
      E := EllipticCurve([1 - c, -b, -b, 0, 0]);       // Tate normal form E_{b,c}
    end if;

    if e[i] lt 0 then E := Twist(E); end if;
  end for;
  return E;
end function;


// ---------------------------------------------------------------- test

SetSeed(1);
E0   := EllipticCurve([F| 0, 0, 0, 1, 0]);                              // y^2 = x^3 + x, #E0 = p + 1
keys := [[Random(-3, 3) : l in ls] : i in [1..5]] cat [[3 : l in ls]];  // 5 random keys and the maximal vector

for e in keys do
  Ev   := Act(E0, e, "velu");
  Eo   := Act(E0, e, "ours");
  back := Act(Eo, [-x : x in e], "ours");
  printf "j = %o:  Velu~ours %o, inverse key gives E0 %o (j(back) = %o)\n",
         jInvariant(Ev), IsIsomorphic(Ev, Eo), IsIsomorphic(back, E0), jInvariant(back);
end for;
